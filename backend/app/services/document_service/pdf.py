"""Premium PDF Document Design Engine for HSBot.

Renders executive-grade PDF reports, whitepapers, proposals, and resumes with:
- Modern Cover Page with color bands, metadata blocks, and accent lines
- Running headers and footers with dynamic 'Page X of Y' via NumberedCanvas
- Table of Contents for multi-section documents
- Callout quote boxes with left accent borders
- Metric / KPI summary grids
- Step-by-step workflow / pipeline visual blocks
- Styled data tables with themed headers and alternating row shading
- Dedicated Resume templates (ATS and Modern)
"""

